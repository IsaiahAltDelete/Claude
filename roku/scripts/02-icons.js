/** Inline SVG for a named glyph. */
function ICON(name, cls) {
  const d = PATHS[name];
  if (!d) return '';
  return `<svg viewBox="0 0 24 24"${cls ? ` class="${cls}"` : ''} aria-hidden="true"><path d="${d}"/></svg>`;
}

/** Bars glyph used for signal strength, 0-4 lit. */
function BARS(level, weak) {
  const lit = clamp(level, 0, 4);
  let out = `<span class="bars${weak ? ' weak' : ''}">`;
  for (let i = 1; i <= 4; i += 1) out += `<i class="${i <= lit ? 'lit' : ''}"></i>`;
  return `${out}</span>`;
}

/** Five stars, filled to the nearest half rounded down. */
function STARS(score) {
  let out = '<span class="stars">';
  for (let i = 1; i <= 5; i += 1) out += `<span class="${i <= Math.round(score) ? '' : 'off'}">★</span>`;
  return `${out}</span>`;
}
